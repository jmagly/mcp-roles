#!/usr/bin/env bash
if [[ -z "${ZSH_VERSION:-}" && "${BASH_VERSINFO[0]:-0}" -lt 4 ]]; then
    printf 'Error: bash 4+ or zsh required (macOS: brew install bash).\n' >&2
    exit 1
fi
set -euo pipefail

script_dir=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck source=lib/core.sh
source "$script_dir/lib/core.sh"
account_home=$(_mcp_roles_account_home)
prefix="$account_home/.local/share/mcp-roles"
providers=''
link_bin=1

usage() {
    printf 'Usage: install.sh [--providers claude,codex,hermes,muse] [--prefix DIR] [--no-link-bin]\n'
}

while [[ "$#" -gt 0 ]]; do
    case "$1" in
        --providers|--prefix)
            [[ "$#" -ge 2 ]] || { usage >&2; exit 2; }
            if [[ "$1" == --providers ]]; then providers="$2"; else prefix="$2"; fi
            shift 2
            ;;
        --no-link-bin) link_bin=0; shift ;;
        *) usage >&2; exit 2 ;;
    esac
done

if [[ -z "$providers" ]]; then
    for provider in claude codex hermes muse; do
        if command -v "$provider" >/dev/null 2>&1; then
            providers="${providers:+$providers,}$provider"
        fi
    done
fi
[[ -n "$providers" ]] || printf 'Warning: no provider CLIs (claude, codex, hermes, muse) found on PATH; no wrappers installed. Re-run with --providers.\n' >&2
IFS=, read -r -a selected <<< "$providers"
for provider in ${selected[@]+"${selected[@]}"}; do
    case "$provider" in
        claude|codex|hermes|muse) ;;
        *) printf 'Unknown provider: %s\n' "$provider" >&2; exit 2 ;;
    esac
done

rc=''
case "${SHELL:-}" in
    */zsh) rc="$account_home/.zshrc" ;;
    */bash) rc="$account_home/.bashrc" ;;
    *) printf 'Warning: unsupported SHELL (%s); skipping rc block.\n' "${SHELL:-unset}" >&2 ;;
esac
if [[ -n "$rc" ]]; then
    if [[ -L "$rc" && ! -e "$rc" ]]; then
        printf 'Error: rc target is a dangling symlink: %s\n' "$rc" >&2
        exit 1
    elif [[ -e "$rc" ]]; then
        [[ -f "$rc" && -w "$rc" ]] || { printf 'Error: rc target is not a writable file: %s\n' "$rc" >&2; exit 1; }
        _mcp_roles_strip_rc_block "$rc" > /dev/null || exit 1
    elif [[ ! -d "$account_home" || ! -w "$account_home" ]]; then
        printf 'Error: cannot create rc target: %s\n' "$rc" >&2
        exit 1
    fi
fi

mkdir -p "$prefix"
prefix=$(cd "$prefix" && pwd -P)
cp -R "$script_dir/lib" "$script_dir/providers" "$script_dir/bin" "$prefix/"
printf 'mcp-roles installation\n' > "$prefix/.mcp-roles-install"
{
    printf '# Generated by mcp-roles install.sh\n'
    # Adapters load only when the core accepted this shell.
    printf 'if source %q; then\n' "$prefix/lib/core.sh"
    for provider in ${selected[@]+"${selected[@]}"}; do
        printf '    source %q\n' "$prefix/providers/$provider.sh"
    done
    printf 'fi\n'
} > "$prefix/init.sh"

catalog=$(_mcp_roles_catalog_dir)
mkdir -p "$catalog"
has_roles=0
for role_file in "$catalog"/*.json; do
    [[ -f "$role_file" ]] || continue
    has_roles=1
    break
done
if [[ "$has_roles" -eq 0 ]]; then
    cp "$script_dir/examples/roles/"*.json "$catalog/"
    printf 'Seeded catalog: %s\n' "$catalog"
fi

if [[ -n "$rc" ]]; then
    touch "$rc"
    rc_temp=$(mktemp "${rc}.tmp.XXXXXX")
    if ! _mcp_roles_strip_rc_block "$rc" > "$rc_temp"; then
        rm -f "$rc_temp"
        exit 1
    fi
    {
        printf '# >>> mcp-roles >>>\n'
        printf 'source %q\n' "$prefix/init.sh"
        printf '# <<< mcp-roles <<<\n'
    } >> "$rc_temp"
    cat "$rc_temp" > "$rc"
    rm -f "$rc_temp"
fi

if [[ "$link_bin" -eq 1 ]]; then
    mkdir -p "$account_home/.local/bin"
    bin_link="$account_home/.local/bin/mcp-roles"
    if [[ ! -e "$bin_link" && ! -L "$bin_link" ]] || [[ -L "$bin_link" && "$(readlink "$bin_link")" == "$prefix/bin/mcp-roles" ]]; then
        ln -sfn "$prefix/bin/mcp-roles" "$bin_link"
    else
        printf 'Skipped occupied command path: %s\n' "$bin_link"
    fi
fi
if [[ -n "$rc" ]]; then
    printf 'Installed to %s; source %s to activate.\n' "$prefix" "$rc"
else
    printf 'Installed to %s; source %s/init.sh to activate.\n' "$prefix" "$prefix"
fi
